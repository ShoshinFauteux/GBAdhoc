#!/usr/bin/env bash
# build_win.sh -- the Windows builds of xmbwrap (WSL/Linux + docker).
#   GBAdhoc-XMB-Maker.exe   the app (one window)
#   xmbwrap.exe             the command line
# Both carry the launcher built in (psp/launcher/EBOOT.PBP -> launcher_pbp.h),
# statically linked: nothing to install.  Output: tools/xmbwrap/dist/.
set -eu
HERE="$(cd "$(dirname "$0")" && pwd)"
TREE="$(cd "$HERE/../.." && pwd)"
TPL="$TREE/psp/launcher/EBOOT.PBP"
[ -f "$TPL" ] || { echo "build psp/launcher first (psp/launcher/Makefile)"; exit 2; }
docker image inspect xmbwrap-mingw >/dev/null 2>&1 || \
  docker build -q -t xmbwrap-mingw -f "$HERE/Dockerfile.mingw" "$HERE" >/dev/null
python3 - "$TPL" "$HERE/launcher_pbp.h" <<'EOF'
import sys
d = open(sys.argv[1], "rb").read()
with open(sys.argv[2], "w") as f:
    f.write("/* generated by build_win.sh from psp/launcher/EBOOT.PBP; do not edit */\n")
    f.write("static const unsigned char xw_launcher_pbp[] = {\n")
    for i in range(0, len(d), 16):
        f.write("  " + ",".join(str(b) for b in d[i:i + 16]) + ",\n")
    f.write("};\nstatic const size_t xw_launcher_pbp_len = %d;\n" % len(d))
EOF
mkdir -p "$HERE/dist"
docker run --rm -v "$HERE":/x -w /x xmbwrap-mingw sh -c '
  set -e
  CC=x86_64-w64-mingw32-gcc
  $CC -O2 -Wall -municode -mwindows -static -o dist/GBAdhoc-XMB-Maker.exe xw_win.c xw_core.c -lcomdlg32 -lgdi32 -lm
  $CC -O2 -Wall -municode -static -DXW_EMBED_TEMPLATE -o dist/xmbwrap.exe xw_cli.c xw_core.c -lm
  x86_64-w64-mingw32-strip dist/*.exe'
ls -la "$HERE/dist"
