#!/usr/bin/env python3
"""mode_switch_gen.py -- CPU mode switch test ROM (MSR_FAST, codegen-q3).

    python3 mode_switch_gen.py gen OUT.s              # write the assembly
    python3 mode_switch_gen.py cmp DUMP_A DUMP_B      # compare two DR_RAMDUMPs

Every ordered pair of the privileged modes (SYS IRQ FIQ SVC ABT UND) is
switched by MSR CPSR_c #imm, MSR CPSR_fc Rn and an SPSR restore (MOVS pc, lr),
with r8-r14 of every bank pre-loaded with distinct values; after each switch
r8-r14 and the CPSR are stored to EWRAM, and at the end every bank is read
back.  Further cases: an SPSR restore into Thumb, LDM ^ with pc (SPSR restore),
a switch to the same mode, and a switch that unmasks a pending timer IRQ (the
fallback to the C path must raise it: the handler counts and records).

The reference is the interpreter (it runs the C set_cpu_mode); run the ROM
with gpsp_boot_mode=game on the dynarec and with gpsp_drc=disabled and compare.
Results from EWRAM 0x02000100; 0x02000000 = 0xC0DE600D, 0x02000004 = end.
"""
import struct, sys

MODES = {"sys": 0x1F, "irq": 0x12, "fiq": 0x11, "svc": 0x13, "abt": 0x17, "und": 0x1B}
I_F = 0xC0     # IRQ + FIQ masked


def gen(out):
    a = []
    E = a.append
    E("@ generated by mode_switch_gen.py -- do not edit")
    E("    .arm")
    E("    .section .text")
    E("    .global _start")
    E("_start:")
    E("    b       init")
    E("    .fill   0xBC, 1, 0")
    E("init:")
    # one stack per mode, distinct r8-r14 per bank
    for k, (name, m) in enumerate(MODES.items()):
        E("    msr     cpsr_fc, #0x%02x" % (m | I_F))
        E("    ldr     sp, =0x%08x" % (0x03007F00 - 0x100 * k))
        if name == "irq":
            E("    ldr     sp, =0x03007FA0")
        E("    ldr     lr, =0x%08x" % (0xE0000000 | (m << 16)))
        if name == "fiq":
            for r in range(8, 13):
                E("    ldr     r%d, =0x%08x" % (r, 0xF0000000 | (r << 16) | m))
    E("    msr     cpsr_fc, #0x%02x" % (0x1F | I_F))
    for r in range(8, 13):
        E("    ldr     r%d, =0x%08x" % (r, 0x80000000 | (r << 16) | 0x1F))
    E("    ldr     r0, =0x02000100")
    E("    ldr     r1, =0x03000000")
    E("    str     r0, [r1]")          # result pointer lives in IWRAM
    E("    b       cases")
    E("    .ltorg")

    # store r8-r14 + CPSR at the result pointer (r0-r2 scratch)
    E("rec:")
    E("    ldr     r1, =0x03000000")
    E("    ldr     r0, [r1]")
    E("    mrs     r2, cpsr")
    E("    stmia   r0!, {r2, r8-r14}")
    E("    str     r0, [r1]")
    E("    bx      r3")
    E("    .ltorg")

    E("cases:")
    n = [0]

    def rec():
        n[0] += 1
        E("    adr     r3, 9f")
        E("    b       rec")
        E("9:")
        if n[0] % 20 == 0:
            E("    b       8f")
            E("    .ltorg")
            E("8:")

    names = list(MODES)
    for x in names:
        for y in names:
            mx, my = MODES[x] | I_F, MODES[y] | I_F
            # 1. MSR CPSR_c, #imm (control field only)
            E("    msr     cpsr_fc, #0x%02x" % mx)
            E("    msr     cpsr_c, #0x%02x" % my)
            rec()
            # 2. MSR CPSR_fc, Rn (I clear, IE=0 so nothing pending), flags set
            E("    msr     cpsr_fc, #0x%02x" % mx)
            E("    ldr     r4, =0x%08x" % (0xA0000000 | MODES[y] | 0x40))
            E("    msr     cpsr_fc, r4")
            rec()
            # 3. SPSR restore: MOVS pc, lr in x with SPSR = y (x has an SPSR)
            if x != "sys":
                E("    msr     cpsr_fc, #0x%02x" % mx)
                E("    ldr     r4, =0x%08x" % (0x50000000 | my))
                E("    msr     spsr_fc, r4")
                E("    mov     r5, lr")
                E("    adr     lr, 7f")
                E("    movs    pc, lr")
                E("7:")
                rec()
                E("    msr     cpsr_fc, #0x%02x" % mx)
                E("    mov     lr, r5")
    # 4. SPSR restore into Thumb (SVC -> SYS|T), back to ARM by BX
    E("    msr     cpsr_fc, #0x%02x" % (0x13 | I_F))
    E("    ldr     r4, =0x%08x" % (0x1F | I_F | 0x20))
    E("    msr     spsr_fc, r4")
    E("    mov     r5, lr")
    E("    adr     lr, th")
    E("    movs    pc, lr")
    E("    .thumb")
    E("    .align  2")
    E("th:")
    E("    mov     r6, r14")
    E("    ldr     r4, =ar")
    E("    bx      r4")
    E("    .ltorg")
    E("    .arm")
    E("    .align  2")
    E("ar:")
    rec()
    E("    msr     cpsr_fc, #0x%02x" % (0x13 | I_F))
    E("    mov     lr, r5")
    # 5. LDM ^ with pc: IRQ -> SVC via the stack
    E("    msr     cpsr_fc, #0x%02x" % (0x12 | I_F))
    E("    ldr     r4, =0x%08x" % (0x60000000 | 0x13 | I_F))
    E("    msr     spsr_fc, r4")
    E("    adr     r4, 6f")
    E("    stmfd   sp!, {r4}")
    E("    ldmfd   sp!, {pc}^")
    E("6:")
    rec()
    # 6. SUBS pc, lr, #4: FIQ -> UND
    E("    msr     cpsr_fc, #0x%02x" % (0x11 | I_F))
    E("    ldr     r4, =0x%08x" % (0x1B | I_F))
    E("    msr     spsr_fc, r4")
    E("    mov     r5, lr")
    E("    adr     lr, 5f + 4")
    E("    subs    pc, lr, #4")
    E("5:")
    rec()
    E("    msr     cpsr_fc, #0x%02x" % (0x11 | I_F))
    E("    mov     lr, r5")
    # 7. a pending IRQ unmasked by MSR: timer 0 overflow, IME=1, IE=timer0
    E("    msr     cpsr_fc, #0x%02x" % (0x1F | 0x80))
    E("    ldr     r4, =irqh")
    E("    ldr     r1, =0x03007FFC")
    E("    str     r4, [r1]")
    E("    ldr     r1, =0x04000000")
    E("    add     r2, r1, #0x200")
    E("    mov     r4, #8")
    E("    strh    r4, [r2]")             # IE = timer 0 (IF bit 3)
    E("    mov     r4, #1")
    E("    strh    r4, [r2, #8]")         # IME = 1
    E("    ldr     r4, =0x00C0FFF0")      # TM0: reload 0xFFF0, enable + IRQ
    E("    str     r4, [r1, #0x100]")
    E("4:")
    E("    ldrh    r4, [r2, #2]")         # wait for IF.timer0 (masked)
    E("    tst     r4, #8")
    E("    beq     4b")
    E("    mov     r4, #0")
    E("    str     r4, [r1, #0x100]")     # timer off
    E("    ldr     r4, =0x03000004")
    E("    ldr     r6, [r4]")
    E("    msr     cpsr_c, #0x13")        # SYS (I masked) -> SVC, I clear: IRQ now
    E("    ldr     r7, [r4]")             # handler ran once: r7 = r6 + 1
    rec()
    E("    msr     cpsr_c, #0x%02x" % (0x13 | I_F))
    E("    ldr     r1, =0x03000000")
    E("    ldr     r0, [r1]")
    E("    stmia   r0!, {r6, r7}")
    E("    str     r0, [r1]")
    # 8. same-mode switch
    E("    msr     cpsr_c, #0x%02x" % (0x13 | I_F))
    rec()
    # 10. MSR CPSR_c with flags live from an ALU op (not yet in reg[CPSR])
    for x, y in (("sys", "svc"), ("svc", "sys"), ("sys", "fiq"), ("fiq", "irq")):
        E("    msr     cpsr_fc, #0x%02x" % (MODES[x] | I_F))
        E("    mov     r4, #0")
        E("    cmp     r4, #0")                # Z=1 C=1 (reg[CPSR] says 0)
        E("    msr     cpsr_c, #0x%02x" % (MODES[y] | I_F))
        E("    mrs     r4, cpsr")
        E("    movne   r4, #0")                # and the live Z
        E("    ldr     r1, =0x03000000")
        E("    ldr     r0, [r1]")
        E("    stmia   r0!, {r4}")
        E("    str     r0, [r1]")
    # 9. read every bank back
    for name, m in MODES.items():
        E("    msr     cpsr_fc, #0x%02x" % (m | I_F))
        rec()
    E("    ldr     r1, =0x03000000")
    E("    ldr     r0, [r1]")
    E("    ldr     r1, =0x02000000")
    E("    ldr     r2, =0xC0DE600D")
    E("    str     r2, [r1]")
    E("    str     r0, [r1, #4]")
    E("halt:")
    E("    b       halt")
    E("    .ltorg")
    # IRQ handler (called by the BIOS in IRQ mode): count, acknowledge, off
    E("irqh:")
    E("    ldr     r0, =0x03000004")
    E("    ldr     r1, [r0]")
    E("    add     r1, r1, #1")
    E("    str     r1, [r0]")
    E("    ldr     r0, =0x04000200")
    E("    mov     r1, #0")
    E("    strh    r1, [r0]")             # IE = 0
    E("    mov     r1, #8")
    E("    strh    r1, [r0, #2]")         # IF ack
    E("    bx      lr")
    E("    .ltorg")
    open(out, "w").write("\n".join(a) + "\n")
    print("cases:", n[0])


def cmp(da, db):
    A, B = open(da, "rb").read(), open(db, "rb").read()
    ea, eb = A[17 * 4 + 0x8000:], B[17 * 4 + 0x8000:]
    for nm, e in (("A", ea), ("B", eb)):
        mg, end = struct.unpack_from("<II", e, 0)
        if mg != 0xC0DE600D:
            print("%s did not finish (magic %08x)" % (nm, mg))
            return 2
    end = struct.unpack_from("<I", ea, 4)[0]
    endb = struct.unpack_from("<I", eb, 4)[0]
    if end != endb:
        print("end pointers differ %08x %08x" % (end, endb))
        return 1
    ln = end - 0x02000000
    bad = 0
    for o in range(0x100, ln, 4):
        x, y = struct.unpack_from("<I", ea, o)[0], struct.unpack_from("<I", eb, o)[0]
        if x != y:
            bad += 1
            if bad <= 20:
                rec = (o - 0x100) // 32
                print("word +%x (record %d, slot %d): %08x vs %08x" % (o, rec, (o - 0x100) // 4 % 8, x, y))
    print("%d words, %d differ" % ((ln - 0x100) // 4, bad))
    return 1 if bad else 0


if __name__ == "__main__":
    if sys.argv[1] == "gen":
        gen(sys.argv[2])
    else:
        sys.exit(cmp(sys.argv[2], sys.argv[3]))
