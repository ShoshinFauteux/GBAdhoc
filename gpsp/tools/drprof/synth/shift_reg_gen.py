#!/usr/bin/env python3
"""shift_reg_gen.py -- register-specified shift test ROM + its exact reference.

    python3 shift_reg_gen.py gen   OUT.s            # write the assembly (+ OUT.s.json: the case list)
    python3 shift_reg_gen.py check OUT.s.json DUMP  # compare a DR_RAMDUMP of the run against the spec

ARM7TDMI semantics of "Rm, <LSL|LSR|ASR|ROR> Rs" (ARM data processing) and of
Thumb "LSL/LSR/ASR/ROR Rd, Rs": the amount is Rs[7:0] ONLY.  With s = Rs & 0xFF:
s == 0 leaves Rm and C; LSL/LSR 32 give 0 with C = Rm[0] / Rm[31]; LSL/LSR > 32
give 0, C = 0; ASR >= 32 gives Rm[31] everywhere (and in C); ROR rotates by
s & 31 with C = Rm[(s - 1) & 31] (a non-zero multiple of 32 leaves Rm, C = Rm[31]).
Rm == PC reads the instruction address + 12 (ARM).

The reference below is written from that spec (ARM ARM A5.1.6-A5.1.12, Thumb
LSL/LSR/ASR/ROR (2)), not from either engine.  Groups:

  arm_movs   ARM MOVS r2, r0, <sh> r1 ; MRS r3, CPSR    (dynarec flags path)
  arm_mov    ARM MOV  r2, r0, <sh> r1 ; MRS r3, CPSR    (no-flags path; NZCV unchanged)
  arm_add    ARM ADD  r2, r5, r0, <sh> r1               (no-flags path as an operand; r5 = 0x1000)
  arm_same   ARM MOVS r2, r1, <sh> r1                   (Rm == Rs)
  arm_pc     ARM MOV(S) r2, pc, <sh> r1 ; r4 = address of the instruction
  thumb_f    Thumb <sh> r2, r1 with C, Z, N read after  (flags path)
  thumb_nf   Thumb <sh> r2, r1 ; CMP r2, r2             (C dead: no-flags path)

Results are written from EWRAM 0x02000100 as (r2, r3) pairs (arm_pc: r2, r4);
0x02000000 = 0xC0DE600D when the ROM finished, 0x02000004 = end pointer.
Run with gpsp_boot_mode=game on the dynarec AND with gpsp_drc=disabled.
"""
import json, struct, sys

M = 0xFFFFFFFF
OPS = ["lsl", "lsr", "asr", "ror"]
RMS = [0x80000001, 0x40000002, 0xF0F0F00F, 0x7FFFFFFF, 0x00000000]
RSS = [0, 1, 7, 31, 32, 33, 63, 64, 96, 128, 224, 255,
       0x100, 0x101, 0x11F, 0x120, 0x121, 0x1FF, 0x140,
       0xFFFFFF00, 0xFFFFFF20, 0xFFFFFFFF, 0x80000000, 0x8000001F, 0x00010001]
FLAGS = [0x00000000, 0x30000000]          # ARM initial NZCV (C=1,V=1 in the second)


def shift(op, rm, rs, cin):
    """(result, carry) of a register-specified shift, ARM7TDMI."""
    s = rs & 0xFF
    rm &= M
    if s == 0:
        return rm, cin
    if op == "lsl":
        if s < 32:
            return (rm << s) & M, (rm >> (32 - s)) & 1
        if s == 32:
            return 0, rm & 1
        return 0, 0
    if op == "lsr":
        if s < 32:
            return rm >> s, (rm >> (s - 1)) & 1
        if s == 32:
            return 0, rm >> 31
        return 0, 0
    if op == "asr":
        sign = rm >> 31
        if s < 32:
            v = (rm - (1 << 32)) if sign else rm
            return (v >> s) & M, (rm >> (s - 1)) & 1
        return (M if sign else 0), sign
    if op == "ror":
        r = s & 31
        res = ((rm >> r) | (rm << (32 - r))) & M if r else rm
        return res, (rm >> ((s - 1) & 31)) & 1
    raise ValueError(op)


def nz(v):
    return ((v >> 31) & 1) << 31 | (1 << 30 if v == 0 else 0)


def gen(out):
    a = []     # assembly lines
    cases = []
    E = a.append
    E("@ generated by shift_reg_gen.py -- do not edit")
    E("    .arm")
    E("    .section .text")
    E("    .global _start")
    E("_start:")
    E("    b       init")
    E("    .fill   0xBC, 1, 0")
    E("init:")
    E("    ldr     sp, =0x03007F00")
    E("    ldr     r10, =0x02000100")
    E("    mov     r5, #0x1000")
    n = [0]

    def pool_arm():
        n[0] += 1
        if n[0] % 40 == 0:
            E("    b       1f")
            E("    .ltorg")
            E("1:")

    # ARM MOVS / MOV / ADD / Rm == Rs
    for op in OPS:
        for rm in RMS:
            for rs in RSS:
                for fl in FLAGS:
                    cin = (fl >> 29) & 1
                    res, c = shift(op, rm, rs, cin)
                    E("    ldr     r0, =0x%08x" % rm)
                    E("    ldr     r1, =0x%08x" % rs)
                    E("    ldr     r6, =0x%08x" % fl)
                    E("    msr     cpsr_f, r6")
                    E("    movs    r2, r0, %s r1" % op)
                    E("    mrs     r3, cpsr")
                    E("    stmia   r10!, {r2, r3}")
                    cases.append(dict(g="arm_movs", op=op, rm=rm, rs=rs, fl=fl,
                                      r2=res, nzcv=nz(res) | c << 29 | (fl & 0x10000000)))
                    pool_arm()
                fl = 0xF0000000
                res, c = shift(op, rm, rs, 1)
                E("    ldr     r0, =0x%08x" % rm)
                E("    ldr     r1, =0x%08x" % rs)
                E("    ldr     r6, =0x%08x" % fl)
                E("    msr     cpsr_f, r6")
                E("    mov     r2, r0, %s r1" % op)
                E("    mrs     r3, cpsr")
                E("    stmia   r10!, {r2, r3}")
                cases.append(dict(g="arm_mov", op=op, rm=rm, rs=rs, fl=fl, r2=res, nzcv=fl))
                pool_arm()
                E("    ldr     r0, =0x%08x" % rm)
                E("    ldr     r1, =0x%08x" % rs)
                E("    add     r2, r5, r0, %s r1" % op)
                E("    mov     r3, #0")
                E("    stmia   r10!, {r2, r3}")
                cases.append(dict(g="arm_add", op=op, rm=rm, rs=rs, r2=(0x1000 + res) & M, nzcv=None))
                pool_arm()
        for rs in RSS:
            for fl in FLAGS:
                cin = (fl >> 29) & 1
                res, c = shift(op, rs, rs, cin)
                E("    ldr     r1, =0x%08x" % rs)
                E("    ldr     r6, =0x%08x" % fl)
                E("    msr     cpsr_f, r6")
                E("    movs    r2, r1, %s r1" % op)
                E("    mrs     r3, cpsr")
                E("    stmia   r10!, {r2, r3}")
                cases.append(dict(g="arm_same", op=op, rm=rs, rs=rs, fl=fl,
                                  r2=res, nzcv=nz(res) | c << 29 | (fl & 0x10000000)))
                pool_arm()
    # Rm == PC (reads the instruction address + 12)
    k = 0
    for op in OPS:
        for rs in [0, 1, 4, 0x100, 0x101, 32, 0x21]:
            for s_ in ("", "s"):
                k += 1
                E("    ldr     r1, =0x%08x" % rs)
                E("    ldr     r6, =0x20000000")
                E("    msr     cpsr_f, r6")
                E("    adr     r4, pcx%d" % k)
                E("pcx%d:" % k)
                E("    mov%s   r2, pc, %s r1" % (s_, op))
                E("    stmia   r10!, {r2, r4}")
                cases.append(dict(g="arm_pc", op=op, rs=rs, s=s_))
                pool_arm()
    E("    b       1f")
    E("    .ltorg")
    E("1:")
    # Thumb
    E("    ldr     r7, =0")
    E("    mov     r7, r10")
    E("    mov     r8, #1")
    E("    mov     r9, #2")
    E("    mov     r11, #4")
    E("    adr     r12, thumb_tests + 1")
    E("    bx      r12")
    E("    .ltorg")
    E("    .thumb")
    E("    .align  2")
    E("thumb_tests:")
    t = [0]

    def pool_thumb():
        t[0] += 1
        if t[0] % 6 == 0:
            E("    b       1f")
            E("    .align  2")
            E("    .pool")
            E("1:")

    for op in OPS:
        for rm in RMS:
            for rs in RSS:
                for cin in (0, 1):
                    res, c = shift(op, rm, rs, cin)
                    E("    ldr     r2, =0x%08x" % rm)
                    E("    ldr     r1, =0x%08x" % rs)
                    E("    mov     r3, #0")
                    E("    mov     r4, #%d" % cin)
                    E("    lsr     r4, r4, #1")
                    E("    %s     r2, r1" % op)
                    E("    bcc     1f")
                    E("    add     r3, r8")
                    E("1:  bne     2f")
                    E("    add     r3, r9")
                    E("2:  bpl     3f")
                    E("    add     r3, r11")
                    E("3:  stmia   r7!, {r2, r3}")
                    cases.append(dict(g="thumb_f", op=op, rm=rm, rs=rs, cin=cin, r2=res,
                                      r3=c | (2 if res == 0 else 0) | (4 if res >> 31 else 0)))
                    pool_thumb()
                E("    ldr     r2, =0x%08x" % rm)
                E("    ldr     r1, =0x%08x" % rs)
                E("    mov     r3, #0")
                E("    %s     r2, r1" % op)
                E("    cmp     r2, r2")
                E("    stmia   r7!, {r2, r3}")
                cases.append(dict(g="thumb_nf", op=op, rm=rm, rs=rs, r2=res, r3=0))
                pool_thumb()
    E("    b       1f")
    E("    .align  2")
    E("    .pool")
    E("1:")
    E("    ldr     r0, =0x02000000")
    E("    ldr     r1, =0xC0DE600D")
    E("    str     r1, [r0]")
    E("    str     r7, [r0, #4]")
    E("done:")
    E("    b       done")
    E("    .align  2")
    E("    .pool")
    open(out, "w").write("\n".join(a) + "\n")
    json.dump(cases, open(out + ".json", "w"))
    print("%d cases, %d asm lines" % (len(cases), len(a)))


def check(js, dump, quiet=False):
    cases = json.load(open(js))
    d = open(dump, "rb").read()
    ew = d[17 * 4 + 0x8000:]
    magic, endp = struct.unpack_from("<II", ew, 0)
    if magic != 0xC0DE600D:
        print("ROM did not finish (magic %08x)" % magic)
        return 2
    want_end = 0x02000100 + 8 * len(cases)
    if endp != want_end:
        print("end pointer %08x != %08x" % (endp, want_end))
        return 2
    bad = {}
    nb = 0
    for i, c in enumerate(cases):
        r2, r3 = struct.unpack_from("<II", ew, 0x100 + 8 * i)
        g = c["g"]
        if g == "arm_pc":
            base = (r3 + 12) & M
            res, cc = shift(c["op"], base, c["rs"], 1)
            ok = r2 == res
            exp = "%08x (pc+12=%08x)" % (res, base)
            got = "%08x" % r2
        elif g in ("arm_movs", "arm_mov", "arm_same"):
            ok = r2 == c["r2"] and (r3 & 0xF0000000) == c["nzcv"]
            exp = "%08x nzcv=%x" % (c["r2"], c["nzcv"] >> 28)
            got = "%08x nzcv=%x" % (r2, r3 >> 28)
        elif g == "arm_add":
            ok = r2 == c["r2"]
            exp, got = "%08x" % c["r2"], "%08x" % r2
        else:
            ok = r2 == c["r2"] and r3 == c["r3"]
            exp = "%08x c/z/n=%d" % (c["r2"], c["r3"])
            got = "%08x c/z/n=%d" % (r2, r3)
        if not ok:
            nb += 1
            k = (g, c["op"])
            bad.setdefault(k, []).append("rm=%08x rs=%08x%s exp %s got %s" % (
                c.get("rm", 0), c["rs"], " cin=%d" % c["cin"] if "cin" in c else
                (" fl=%x" % (c["fl"] >> 28) if "fl" in c else ""), exp, got))
    print("%d cases, %d mismatches" % (len(cases), nb))
    if not quiet:
        for k, v in sorted(bad.items()):
            print("  %-9s %s: %d bad, e.g." % (k[0], k[1], len(v)))
            for x in v[:4]:
                print("      " + x)
    return 1 if nb else 0


if __name__ == "__main__":
    if sys.argv[1] == "gen":
        gen(sys.argv[2])
    elif sys.argv[1] == "check":
        sys.exit(check(sys.argv[2], sys.argv[3], "-q" in sys.argv))
