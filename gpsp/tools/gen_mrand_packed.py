#!/usr/bin/env python3
"""gen_mrand_packed.py -- pack TGB Dual's noise tables 8 bits to a byte.

    gen_mrand_packed.py UNPACKED_H OUT_H      write the packed header
    gen_mrand_packed.py --check UNPACKED_H PACKED_H

UNPACKED_H is the vendored `_mrand_table.h` with one 0/1 byte per bit
(`git show 8f84303:gbcore/tgbdual/_mrand_table.h`, the pristine import, 2 x
32,768 B).  Bit i of a table goes to byte i >> 3, bit i & 7 (LSB first),
which is what MRAND_BIT() in the packed header reads.  --check proves every
bit equal.
"""
import re
import sys


def tables(text):
    out = {}
    for name in ("_mrand7", "_mrand15"):
        m = re.search(r"(?:const\s+)?unsigned char %s\[\][^{]*\{([^}]*)\}" % name, text)
        if not m:
            raise SystemExit("%s not found" % name)
        out[name] = [int(v) for v in re.findall(r"\d+", m.group(1))]
    return out


def packed_tables(text):
    out = {}
    for name in ("_mrand7", "_mrand15"):
        m = re.search(r"const unsigned char %s\[MRAND_PACKED_BYTES\][^{]*\{([^}]*)\}" % name, text)
        if not m:
            raise SystemExit("packed %s not found" % name)
        out[name] = [int(v, 16) for v in re.findall(r"0x([0-9a-f]{2})", m.group(1))]
    return out


def pack(bits):
    if len(bits) != 32768 or set(bits) - {0, 1}:
        raise SystemExit("expected 32768 0/1 values, got %d (%s)" % (len(bits), sorted(set(bits))[:4]))
    b = bytearray(len(bits) // 8)
    for i, v in enumerate(bits):
        if v:
            b[i >> 3] |= 1 << (i & 7)
    return b


HEAD = """//

#define MAX_MRAND  (0x8000) // 32768
#define MASK_MRAND (MAX_MRAND-1) // 0x7FFF

/* GBAdhoc: the noise channel's random bits, read-only and the same for every
 * machine, so they are defined once, in tgb_shared.c, outside the partial
 * link that is copied per instance (gbcore/gbcore.h): the second Game Boy of
 * a link session does not carry its own copy.  apu.c sees only the
 * declarations.
 *
 * Packed 8 bits to a byte (round 9 of the PSP-1000 review): upstream kept
 * one 0/1 byte per bit, 2 x 32 KiB of .rodata; this is 2 x 4 KiB, and the
 * noise channel reads 4 KiB, not 32 KiB, of D-cache per table.  Bit i is
 * byte i >> 3, bit i & 7.  Generated by tools/gen_mrand_packed.py from the
 * pristine import (8f84303); `--check` proves every bit equal. */
#define _mrand7 tgbshared_mrand7
#define _mrand15 tgbshared_mrand15
#define MRAND_PACKED_BYTES (MAX_MRAND / 8)
#define MRAND_BIT(tbl, i) \\
	(((tbl)[((i) & MASK_MRAND) >> 3] >> ((i) & 7)) & 1)
#ifndef TGB_SHARED_TABLES
extern const unsigned char _mrand7[MRAND_PACKED_BYTES], _mrand15[MRAND_PACKED_BYTES];
#else
"""


def emit(name, b):
    lines = ["const unsigned char %s[MRAND_PACKED_BYTES] =" % name, "{"]
    for i in range(0, len(b), 16):
        lines.append(",".join("0x%02x" % v for v in b[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main(argv):
    if len(argv) == 4 and argv[1] == "--check":
        src = tables(open(argv[2], encoding="latin-1").read())
        got = packed_tables(open(argv[3], encoding="latin-1").read())
        bad = 0
        for name in src:
            if bytes(pack(src[name])) != bytes(got[name]):
                print("%s differs" % name)
                bad += 1
            else:
                print("%s: %d bits identical" % (name, len(src[name])))
        return 1 if bad else 0
    if len(argv) != 3:
        print(__doc__)
        return 2
    src = tables(open(argv[1], encoding="latin-1").read())
    body = HEAD + "\n" + emit("_mrand7", pack(src["_mrand7"])) + "\n\n" + \
        emit("_mrand15", pack(src["_mrand15"])) + "\n#endif /* TGB_SHARED_TABLES */\n"
    with open(argv[2], "w", encoding="ascii", newline="\n") as f:
        f.write(body)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
